import { expect, it } from 'vitest';
import { missingBlocks, normalizeRanges } from '../../src/RangeSet';
import type { BlockRange } from '../../src/RangeSet';
import { validateResumeEpoch } from '../../src/EpochManager';
import { generatedRange } from '../../../../tests/helpers/streaming-transfer';

for (const seed of [1, 17, 4099, 0x1badb002, 0x7fffffff])
  it(`seed ${seed}: committed and missing domains are disjoint, exact and duplicate-safe across 256 schedules`, () => {
    let state = seed;
    const next = () => {
      state ^= state << 13;
      state ^= state >>> 17;
      state ^= state << 5;
      return state >>> 0;
    };
    for (let round = 0; round < 256; round++) {
      const total = next() % 513;
      const have = Array.from({ length: total }, () => next() % 3 === 0);
      const input: BlockRange[] = have.flatMap((present, index) =>
        present ? [[index, index] as const] : [],
      );
      for (let i = input.length - 1; i > 0; i--) {
        const j = next() % (i + 1);
        [input[i], input[j]] = [input[j]!, input[i]!];
      }
      const before = JSON.stringify(input);
      const committed = normalizeRanges(input, total);
      const missing = missingBlocks(total, committed);
      const covered = new Uint8Array(total);
      let committedCount = 0,
        missingCount = 0;
      for (const [a, b] of committed)
        for (let index = a; index <= b; index++) {
          expect(have[index]).toBe(true);
          covered[index] = covered[index]! + 1;
          committedCount++;
        }
      for (const [a, b] of missing)
        for (let index = a; index <= b; index++) {
          expect(have[index]).toBe(false);
          covered[index] = covered[index]! + 1;
          missingCount++;
        }
      expect([...covered].every((count) => count === 1)).toBe(true);
      expect(committedCount + missingCount).toBe(total);
      expect(JSON.stringify(input)).toBe(before);
      if (input.length && input.length < total)
        expect(() => normalizeRanges([...input, input[0]!], total)).toThrow();
      expect(() => normalizeRanges([[total, total]], total)).toThrow();
      const roomId = '11111111-1111-4111-8111-111111111111';
      const epoch = (next() % 10000) + 1;
      expect(() => validateResumeEpoch({ roomId, epoch }, { roomId, epoch })).toThrow();
      expect(() =>
        validateResumeEpoch({ roomId, epoch }, { roomId, epoch: epoch + 1 }),
      ).not.toThrow();
    }
  });

it('deterministic generated bytes are independent of read partitioning at block boundaries', () => {
  for (const start of [0, 1, 250, 251, 1024 * 1024 - 13]) {
    const whole = generatedRange(start, 4097);
    const split = new Uint8Array(4097);
    for (let offset = 0; offset < split.length; offset += 37)
      split.set(generatedRange(start + offset, Math.min(37, split.length - offset)), offset);
    expect(split).toEqual(whole);
  }
});

it.each([0, 1, 31, 32, 33, 1024, 65536])(
  'boundary domain %i preserves a complete partition without allocating file bytes',
  (total) => {
    const input: BlockRange[] = total ? [[0, total - 1]] : [];
    expect(missingBlocks(total, input)).toEqual([]);
    expect(missingBlocks(total, [])).toEqual(input);
  },
);
